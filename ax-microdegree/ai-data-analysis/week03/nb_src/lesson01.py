# %%
import pandas as pd

DATA = 'https://raw.githubusercontent.com/Daeil-Noh/Lectures/main/ax-microdegree/ai-data-analysis/data/'
df = pd.read_csv(DATA + 'process.csv')   # 주소 + 파일 이름으로 읽기
df.head()                                # 앞의 5행 보기

# %%
# 몇 행, 몇 열인가?  → (행 수, 열 수)
df.shape

# %%
# 온도(temp) 분포를 막대그래프(히스토그램)로 보기
