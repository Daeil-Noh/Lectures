# ## 5. 인터넷 주소(URL)로 CSV 파일 읽기
# 실습 데이터는 GitHub에 올려 두었습니다. 주소로 읽으면 **업로드할 필요가 없고**, 다음에 열어도 실행만 하면 됩니다.
